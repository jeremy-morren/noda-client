import { Preconditions, RegularYearMonthDayCalculator, YearMonthDay, NewNotImplementedException } from "../internal.ts";
// C#: the GeneratedData base64 string, decoded into these three arrays by the static constructor. noda-js has
// no base64 or static constructor here: tools/NodaJs.Tools (calendars) generates the arrays as the static
// constructor leaves them (index 1 = ComputedMinYear, with the dummy entries at both ends).
import { MonthLengths, YearLengths, YearStartDays } from "./UmAlQuraYearMonthDayCalculatorData.generated.ts";
import { NewInvalidOperationException, type NotImplementedException } from "../internal.ts";

const AverageDaysPer10Years = 3544;

// These four members are generated by UmAlQuraYearMonthDayCalculatorTest.GenerateData.
const ComputedMinYear = 1318;
const ComputedMaxYear = 1500;
const ComputedDaysAtStartOfMinYear = -25448;
// Not ported: GeneratedData (the base64 month lengths; see the import of the generated arrays above)

const ComputedDaysAtStartOfYear1 = ComputedDaysAtStartOfMinYear + Math.trunc(((1 - ComputedMinYear) / 10.0) * AverageDaysPer10Years);
// Precomputed values for lengths of year and lengths of months, populated in the static constructor.
// The number of days in each year, with array index 1 representing ComputedMinYear.
// C#: private static readonly int[] YearLengths; (generated: see the imports)
// A set of 12 bits for each year, indicating the months which are 30 days long instead of 29.
// (Month 1 is set in bit 1, etc. Bit 0 and bits 13-15 are unused.)
// C#: private static readonly ushort[] MonthLengths; (generated: see the imports)
// Number of days from ComputedMinYear on a per year basis.
// C#: private static readonly int[] YearStartDays; (generated: see the imports)

// Not ported: the static constructor (it decodes GeneratedData; the arrays are generated instead)

/**
 * Implementation of the Um Al Qura calendar, using the tabular data in the BCL. This is fetched
 * on construction and cached - we just need to know the length of each month of each year, which is
 * cheap as the current implementation only covers 183 years.
 * @internal
 */
export class UmAlQuraYearMonthDayCalculator extends RegularYearMonthDayCalculator {
  private constructor() {
    super(ComputedMinYear, ComputedMaxYear, 12, AverageDaysPer10Years, ComputedDaysAtStartOfYear1);
  }

  /** C#: `internal UmAlQuraYearMonthDayCalculator()` */
  static New(): UmAlQuraYearMonthDayCalculator {
    return new UmAlQuraYearMonthDayCalculator();
  }

  // No need to use the YearMonthDayCalculator cache, given that we've got the value in array already.
  override GetStartOfYearInDays(year: number): number {
    return YearStartDays[year - ComputedMinYear + 1]!;
  }

  // C#: [ExcludeFromCodeCoverage]
  protected override CalculateStartOfYearDays(year: number): number {
    void year;
    // Only called from the base GetStartOfYearInDays implementation.
    // C#: throw new NotImplementedException(); (noda-js has no NotImplementedException)
    throw NewNotImplementedException();
  }

  protected override GetDaysFromStartOfYearToStartOfMonth(year: number, month: number): number {
    // While we could do something clever to find the Hamming distance on the masked value here,
    // it's considerably simpler just to iterate...
    const monthBits = MonthLengths[year - ComputedMinYear + 1]!;
    let extraDays = 0;
    for (let i = 1; i < month; i++) {
      extraDays += (monthBits >> i) & 1;
    }
    return (month - 1) * 29 + extraDays;
  }

  override GetDaysInMonth(year: number, month: number): number {
    const monthBits = MonthLengths[year - ComputedMinYear + 1]!;
    return 29 + ((monthBits >> month) & 1);
  }

  override GetDaysInYear(year: number): number {
    // Fine for one year either side of min/max.
    return YearLengths[year - ComputedMinYear + 1]!;
  }

  protected override GetYearMonthDayFromYearAndDayOfYear(year: number, dayOfYear: number): YearMonthDay {
    let daysLeft = dayOfYear;
    const monthBits = MonthLengths[year - ComputedMinYear + 1]!;
    for (let month = 1; month <= 12; month++) {
      const monthLength = 29 + ((monthBits >> month) & 1);
      if (daysLeft <= monthLength) {
        return YearMonthDay.NewYearMonthDay(year, month, daysLeft);
      }
      daysLeft -= monthLength;
    }
    // This should throw...
    Preconditions.CheckArgumentRange("dayOfYear", dayOfYear, 1, this.GetDaysInYear(year));
    throw NewInvalidOperationException(`Bug in Noda Time: year ${year} has ${this.GetDaysInYear(year)} days but ${dayOfYear} isn't valid`);
  }

  override IsLeapYear(year: number): boolean {
    return YearLengths[year - ComputedMinYear + 1] === 355;
  }
}
